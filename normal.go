// GetNormalSampler returns a sampler function for the normal distribution.
//
// Distribution: Normal (Gaussian)
//
// Parameters:
//   - mu: mean
//   - sigma:standard deviation (> 0)
//
// The probability density function is:
//
//	f(x) = 1 / sqrt(2 * pi * sigma^2) *
//	       exp(-(x - mu)^2 / (2 * sigma^2)),  for -∞ < x < ∞
//
// Example:
//
//	sampler, _ := r.GetNormalSampler(1.0, 2.0)
//	x := sampler()
func (rng *Random) GetNormalSampler(mu float64, sigma float64) (func() float64, error) {
	if sigma <= 0.0 {
		return nil, fmt.Errorf("invalid parameter: sigma must be positive")
	}
	return func() float64 { return mu + sigma*rng.Normal() }, nil
}

// Normal returns a standard normal random variate
func (rng *Random) Normal() float64 {
	for {
		j := rng.Uint64()
		i := 0xFF & j // This is the selected box
		sign := 0x100 & j
		j = j >> 11 // So we use different bits for i, j, and sign
		if j < kn[i] {
			if sign > 0 {
				return float64(j) * wn[i]
			}
			return -float64(j) * wn[i]
		}
		if i == 0 { // Fallback
			for {
				u1 := rng.Uniform()
				u2 := rng.Uniform()
				for u1 == 0 {
					u1 = rng.Uniform()
				}
				for u2 == 0 {
					u2 = rng.Uniform()
				}
				x := -math.Log(u1) * (1.0 / 3.65415288536100877)
				y := -math.Log(u2)
				if y+y >= x*x {
					if sign > 0 {
						return 3.65415288536100877 + x
					}
					return -3.65415288536100877 - x
				}
			}
		}
		x := float64(j) * wn[i]
		if (fn[i]-fn[i-1])*rng.Uniform() < math.Exp(-0.5*x*x)-fn[i-1] {
			if sign > 0 {
				return -x
			}
			return x
		}
	}
}

