// GetExponentialSampler returns a sampler function for the exponential distribution.
//
// Distribution: Exponential
//
// Parameters:
//   - lambda: rate parameter (> 0)
//
// The probability density function is:
//
//	f(x) = lambda * exp(-lambda * x),  for x ≥ 0
//	     = 0,                          otherwise
//
// Example:
//
//	sampler, _ := r.GetExponentialSampler(2.0)
//	x := sampler()
func (rng *Random) GetExponentialSampler(lambda float64) (func() float64, error) {
	if lambda <= 0.0 {
		return nil, fmt.Errorf("invalid parameter: lambda must be positive")
	}
	return func() float64 { return rng.Exponential() / lambda }, nil
}

// Exponential returns an exponential variable with rate 1
func (rng *Random) Exponential() float64 {
	for {
		j := rng.Uint64()
		i := 0xFF & j // This is the selected box
		j = j >> 11   // So we use different bits for i and j
		if j < ke[i] {
			return float64(j) * we[i]
		}
		if i == 0 {
			u := rng.Uniform()
			for u == 0 {
				u = rng.Uniform()
			}
			return 7.69711747013104971 - math.Log(u)
		}
		x := float64(j) * we[i]
		if (fe[i]-fe[i-1])*rng.Uniform() < math.Exp(-x)-fe[i-1] {
			return x
		}
	}
}

