/*
Exponential random variate generator.

This file implements sampling from the exponential distribution using
the ziggurat method, which provides fast generation via a combination
of table lookup and rejection sampling.

Reference:

G. Marsaglia and W. W. Tsang.
The Ziggurat Method for Generating Random Variables.
Journal of Statistical Software, 5(8), 2000.
*/

package random

