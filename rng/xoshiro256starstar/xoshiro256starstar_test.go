package xoshiro256starstar

import "testing"

// this test generates random numbers and mixes jumps and long jumps
func TestXoshiro256starstar(t *testing.T) {
	// Generated with xoshiro256plusplus_test.c in tools/rng
	xoshiro256starstardata := [...]uint64{18445776030015110841, 16074944618131395832, 12666049466380162274, 6959763153063108458, 17392840434610135973,
		3475529976411785713, 5090562959599709320, 14913085620055549836, 12209205586964070319, 10266937741125774326,
		11301495669239555100, 5989241508946272409, 17640518722188460041, 8949294038712351219, 3936705226640752205,
		7444960895389253258, 6495772875503921697, 13073453969431236631, 11000827859937142985, 15918391611057438316,
		5086116126906104669, 18089075213454438512, 9744656678265601420, 722524338853841124, 5103477956615831536,
		1367704099490347644, 6403238027319908382, 18426072560917855840, 14715845182766269425, 4387122308378372504,
		10180134619379733423, 2297924708764339429, 8204736659915155294, 6475834970674727506, 8244243881553226653,
		1485450104450733168, 13857574034974988908, 16705364477160744274, 8283130631400578428, 14157766150754069616,
		10460461546356694199, 8144070864389979599, 9608722844187726247, 12869754562959146216, 8168175950911672302,
		7835009968225567812, 11718424309857033, 10078937776564558066, 4836923429183586890, 8675529192463018957,
		16944690435508404084}
	rng := New(987654321)

	for i := 0; i < 10; i++ {
		for j := 0; j < 5; j++ {
			got := rng.Uint64()
			want := xoshiro256starstardata[i*5+j]
			if got != want {
				t.Fatalf("step %d: got %d, want %d", i, got, want)
			}
		}
		if i%2 != 0 {
			rng.Jump()
		} else {
			rng.Longjump()
		}
	}
}
