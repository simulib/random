package xoshiro512plusplus

import "testing"

// this test generates random numbers and mixes jumps and long jumps
func TestXoshiro512plusplus(t *testing.T) {
	// Generated with xoshiro512plusplus_test.c in tools/rng
	xoshiro512plusplusdata := [...]uint64{7891063201353697006, 8327102065729071334, 17673092215535690877, 5079275888633106982, 3133156227146243889,
		5719844906512263220, 6389106643694325464, 3864821827836322207, 139601609281802789, 14619969191059002866,
		14695837588011010276, 15004986636029024902, 6743813266323001883, 12477965791668580431, 235031474439332560,
		9454253622306160106, 13830641879784336488, 1528496797861490362, 757396678976647517, 2328903444696511200,
		5043669669033700106, 5858235238137596701, 4576265813638011807, 8506956033437873115, 4177530093327295716,
		7356384785308593160, 13134861114323910135, 4639335685452074892, 13634365804429368044, 5719425999374373836,
		16146577647701456568, 10611302890597619665, 2566473351660097720, 12639302361062663954, 2705530936465411063,
		10210517584260532286, 7296955890274362367, 8768872251768455374, 7191048296153695112, 5946541124511727136,
		9784005110733579042, 1950013264274892422, 10784870190444923032, 3208161182085365674, 3309129689295644891,
		12080507281844854008, 17262732798618036546, 3215286310977293496, 10755519901227217347, 4427790525970609423,
		11053210829639456241}
	rng := New(987654321)

	for i := 0; i < 10; i++ {
		for j := 0; j < 5; j++ {
			got := rng.Uint64()
			want := xoshiro512plusplusdata[i*5+j]
			if got != want {
				t.Fatalf("step %d: got %d, want %d", i*5+j, got, want)
			}
		}
		if i%2 != 0 {
			rng.Jump()
		} else {
			rng.Longjump()
		}
	}
}
