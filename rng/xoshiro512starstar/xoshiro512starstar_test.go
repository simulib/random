package xoshiro512starstar

import "testing"

// this test generates random numbers and mixes jumps and long jumps
func TestXoshiro512starstar(t *testing.T) {
	// Generated with xoshiro512plusplus_test.c in tools/rng
	xoshiro512starstardata := [...]uint64{18445776030015110841, 16074944618131395832, 14331207289056494180, 2203775511811586849, 12302833846208678310,
		7762239494136792536, 6833168530617843177, 8829784627891581913, 10956774373288946789, 14818959880739833248,
		11851905656348168984, 10710859005995930903, 469744178012443171, 17984266488609343547, 11454669432734210809,
		13017784491494971350, 17232372089101116191, 10091270291405238759, 7349799204852767750, 86016244774559619,
		9913284991635314097, 1590105355271708707, 14627026184886100361, 8881759076485033074, 13690564423647472492,
		4996779581014729793, 12163373165606860152, 15969889122991971467, 7058969447198133405, 2673899138817690228,
		3844825913938950819, 11830744595685082060, 16780071077437368200, 1598637574620661090, 10585780822871193322,
		3064640783271708047, 5720763839657273329, 9075226064737440902, 5162706860010889559, 11141356562805019725,
		3413003326707704268, 1600275438517159084, 1854657175183178865, 6297798410203953629, 2018961075196265530,
		9297156238174865634, 2376491063366620700, 6311236447918448057, 16605131703808062384, 8457460383521822970,
		9131626075918227723}
	rng := New(987654321)

	for i := 0; i < 10; i++ {
		for j := 0; j < 5; j++ {
			got := rng.Uint64()
			want := xoshiro512starstardata[i*5+j]
			if got != want {
				t.Fatalf("step %d: got %d, want %d", i*5+j, got, want)
			}
		}
		if i%2 != 0 {
			rng.Jump()
		} else {
			rng.Longjump()
		}
	}
}
