package xoshiro256plusplus

import "testing"

// this test generates random numbers and mixes jumps and long jumps
func TestSplitMix64(t *testing.T) {
	// Generated with xoshiro256plusplus_test.c in tools/rng
	xoshiro256plusplusdata := [...]uint64{13431542649681443305, 15542321868591172780, 13512902244017759209, 2850393548147712216, 8545981514365856994,
		9281312953961141321, 5226571031975708763, 13993122149490010656, 8307569148342716897, 3813545111706953338,
		17330547299826300540, 9879737653560794205, 5686453596895119169, 7105407922017918493, 17911420693224521635,
		3254788774059684997, 8554449602275541434, 1211761379585268372, 12780399469309446964, 9340872086697183828,
		3444502980457269557, 5658956981083348354, 3906630026040883262, 12380599325017282770, 951722410266889068,
		6532335205553629322, 2130167607324039105, 6014659749367860835, 5057912306623299736, 13823467311896783551,
		3355521786879086697, 469070988340722641, 14263544007938755, 5880313320795605337, 3820033827051142710,
		7708169744782857474, 825503261959298114, 9897624114886218180, 7411780525787940596, 12861882570027243174,
		434779732730736853, 10891045237373171595, 12105377486319184585, 12600121453093713237, 14965450784861659376,
		11055275696993798069, 16382288257171449086, 17722374186031618365, 16852061320061534991, 12166819433947554363,
		5470962373259863201}
	rng := New(987654321)

	for i := 0; i < 10; i++ {
		for j := 0; j < 5; j++ {
			got := rng.Uint64()
			want := xoshiro256plusplusdata[i*5+j]
			if got != want {
				t.Fatalf("step %d: got %d, want %d", i, got, want)
			}
		}
		if i%2 != 0 {
			rng.Jump()
		} else {
			rng.Longjump()
		}
	}
}
